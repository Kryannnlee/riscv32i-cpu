`timescale 1ns/1ps
`default_nettype none

// ============================================================
// adder -- 32 位加法器
//
// 用途：算 PC+4、算分支目标地址这类"地址加法"。
// 纯组合逻辑：输出随输入立即变化，没有时钟，也不存任何状态。
//
// 说明：当前 cpu_top / cpu_pipe 里是直接用 `+` 运算符写的
//      （assign pc_plus4 = pc + 32'd4），并没有例化本模块。
//      综合器会把 `+` 映射成同样的 LUT + 进位链，结果一致。
//      保留它是为了留一个"加法器长什么样"的最小样板。
//
// 输入：a, b  -- 两个 32 位操作数
// 输出：sum    -- a + b，超出 32 位的进位直接丢弃（地址回绕正是这种行为）
// ============================================================
module adder (
    input  logic [31:0] a,
    input  logic [31:0] b,
    output logic [31:0] sum
);

    assign sum = a + b;

endmodule
`default_nettype wire
