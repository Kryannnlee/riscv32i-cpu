`timescale 1ns/1ps
`default_nettype none

// ============================================================
// imem -- 指令存储器（只读，1KB，256 个 32 位字）
//
// 作用：给定 PC，取出那条 32 位指令。
// 纯组合读：地址一变，指令当拍就出来（IF 级要靠这个速度）。
//
// 为什么和 dmem 分开：
//   IF 和 MEM 是流水线里两个不同的级，可能同一拍都在访存。
//   分开成两套存储，两条通路互不干扰。
//
// 地址换算：
//   PC 是**字节地址**，每隔 4 递增。数组按字编号，
//   所以要用 addr[31:2]（= addr/4）做下标。
//
// ! 仿真专用的局限：
//   下面的程序是 `initial` 里写死的，只在仿真时存在。
//   上板时这份初值不存在，必须改成 $readmemh 从 .hex 文件加载。
//   同时这也意味着 imem_tb / cpu_tb 断言的是"这份程序的内容"，
//   改程序就得同步改这两个 testbench（耦合点，见 docs/commands.md 末尾）。
// ============================================================
module imem (
    input  logic [31:0] addr,     // 字节地址（来自 PC）
    output logic [31:0] instr     // 取出的 32 位指令
);
    // 256 个 32 位字 = 1KB。索引范围 0~255，正好够 PC 低 10 位。
    // rom_style=distributed：强制用 LUT 拼 ROM，保证组合读
    (* rom_style = "distributed" *) logic [31:0] mem [0:255];

    // 组合读：丢掉低 2 位（字节地址 -> 字下标）
    assign instr = mem[addr[31:2]];

    // -- 测试程序（仅仿真；上板时改用 $readmemh）----------------
    // 覆盖：转发 / load-use 停顿 / 分支冲刷
    //
    // 注意第一行：先把 256 个位置全部填成 NOP（addi x0, x0, 0）。
    // 不填的话 mem[28..255] 是 X，综合器会把它们当"don't care"优化掉，
    // 程序跑完后 PC 取到未定义内容 -> X 传播 -> PC 变成 X -> LED 亮着不闪。
    initial begin
        for (int i = 0; i < 256; i++)
            mem[i] = 32'h00000013;   // NOP

        // ---- 转发（6b）----
        mem[0]  = 32'h00500093;   // addi x1, x0, 5    -> x1 = 5
        mem[1]  = 32'h00108133;   // add  x2, x1, x1   -> x2 = 10（相邻：EX/MEM）
        mem[2]  = 32'h00800193;   // addi x3, x0, 8    -> x3 = 8
        mem[3]  = 32'h00310233;   // add  x4, x2, x3   -> x4 = 18（MEM/WB + EX/MEM）
        mem[4]  = 32'h0041A023;   // sw   x4, 0(x3)    -> DMEM[8] = 18
        mem[5]  = 32'h06300313;   // addi x6, x0, 99   -> x6 = 99

        // ---- load-use（6c）----
        mem[6]  = 32'h0001A283;   // lw   x5, 0(x3)    -> x5 = 18
        mem[7]  = 32'h005283B3;   // add  x7, x5, x5   -> x7 = 36  * 真相关，停一拍
        mem[8]  = 32'h0001A503;   // lw   x10, 0(x3)   -> x10 = 18
        mem[9]  = 32'h00A00493;   // addi x9, x0, 10   -> x9 = 10  * 假相关，不该停

        // ---- 控制冒险（6d）----
        mem[10] = 32'h00300593;   // addi x11, x0, 3   -> x11 = 3
        mem[11] = 32'h00108463;   // beq  x1, x1, +8   -> 相等，跳到 mem[13]，跳过 mem[12]
        mem[12] = 32'h06F00593;   // addi x11, x0, 111 （毒药，不该执行）
        mem[13] = 32'h00209463;   // bne  x1, x2, +8   -> 5!=10，跳到 mem[15]，跳过 mem[14]
        mem[14] = 32'h0DE00593;   // addi x11, x0, 222 （毒药，不该执行）
        mem[15] = 32'h00100613;   // addi x12, x0, 1   -> x12 = 1
        mem[16] = 32'h00109463;   // bne  x1, x1, +8   -> 相等，不跳，往下走
        mem[17] = 32'h00200613;   // addi x12, x0, 2   -> x12 = 2（若上面误跳，这里会被跳过）

        // ---- 跳转与 U 型（指令集补齐）----
        mem[18] = 32'h00C000EF;   // jal  x1, +12       -> x1 = 76（返回地址），跳到 mem[21]
        mem[19] = 32'h22B00593;   // addi x11, x0, 555  （毒药，被跳过）
        mem[20] = 32'h22C00593;   // addi x11, x0, 556  （毒药，被跳过）
        mem[21] = 32'h00100B93;   // addi x23, x0, 1    -> x23 = 1
        mem[22] = 32'h00000A97;   // auipc x21, 0       -> x21 = 自己的 PC = 88
        mem[23] = 32'h010A8A93;   // addi x21, x21, 16  -> x21 = 104（相邻，走 EX/MEM 转发）
        mem[24] = 32'h000A8067;   // jalr x0, 0(x21)    -> 跳到 104（rs1 也是转发来的）
        mem[25] = 32'h30900593;   // addi x11, x0, 777  （毒药，被跳过）
        mem[26] = 32'h00100C13;   // addi x24, x0, 1    -> x24 = 1
        mem[27] = 32'h12345A37;   // lui  x20, 0x12345  -> x20 = 0x12345000
    end

endmodule
`default_nettype wire
